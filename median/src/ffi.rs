//! Panic containment at the FFI boundary.
//!
//! A panic that unwinds out of an `extern "C"` function aborts the process, which for an
//! external means Max itself. Every function that Max can call (methods, attribute accessors,
//! `notify`, `assist`, `new`, `free`, `perform64`, `dsp64`, clock callbacks, `ext_main`) therefore
//! runs the user's code inside one of the `guard*` helpers here. They catch the panic, post the
//! panic message to the Max console, and return a neutral value.
//!
//! This only works if panics unwind: an external built with `panic = "abort"` still aborts.
//! The template and examples build with `panic = "unwind"` for that reason.
//!
//! The `guard*` functions that take an object are for the code generated by `median_macros`
//! and are not part of the stable API.

use crate::object::MaxObjHeader;
use std::{
    any::Any,
    panic::{AssertUnwindSafe, catch_unwind},
};

/// The `t_max_err` that trampolines return when the user's code panicked
/// (`MAX_ERR_GENERIC`).
pub const ERR_GENERIC: max_sys::t_max_err = max_sys::e_max_errorcodes::MAX_ERR_GENERIC as _;

/// Extract the message from a panic payload: `&str` and `String` payloads (what `panic!` with a
/// message produces) are returned, anything else becomes a generic message.
pub(crate) fn payload_message(payload: &(dyn Any + Send)) -> String {
    if let Some(s) = payload.downcast_ref::<&str>() {
        (*s).to_string()
    } else if let Some(s) = payload.downcast_ref::<String>() {
        s.clone()
    } else {
        "unknown panic payload".to_string()
    }
}

/// Run `f`, turning a panic into `Err(message)`.
pub(crate) fn catch<R, F: FnOnce() -> R>(f: F) -> Result<R, String> {
    catch_unwind(AssertUnwindSafe(f)).map_err(|p| payload_message(p.as_ref()))
}

/// Run `f`; if it panics, call `report` with the message and return `neutral`.
pub(crate) fn guard_with<R, F, P>(neutral: R, f: F, report: P) -> R
where
    F: FnOnce() -> R,
    P: FnOnce(&str),
{
    match catch(f) {
        Ok(r) => r,
        Err(msg) => {
            report(&msg);
            neutral
        }
    }
}

pub(crate) fn panic_text(what: &str, msg: &str) -> String {
    format!("median: panic in {}: {}", what, msg)
}

/// Run `f`; on a panic, post the message as an error for `obj` and return `neutral`.
///
/// # Safety
/// `obj` must be null or point to a valid Max object.
pub(crate) unsafe fn guard_raw<R, F: FnOnce() -> R>(
    obj: *mut max_sys::t_object,
    what: &str,
    neutral: R,
    f: F,
) -> R {
    guard_with(neutral, f, |msg| {
        // SAFETY: the caller guarantees `obj` is null or valid
        unsafe { crate::object::error(obj, panic_text(what, msg)) }
    })
}

/// Run `f` for the object `obj`; on a panic, post the message as an error for `obj` and
/// return `neutral`. `what` names the method, for the message.
#[doc(hidden)]
pub fn guard_or<O: MaxObjHeader, R, F: FnOnce() -> R>(obj: &O, what: &str, neutral: R, f: F) -> R {
    // SAFETY: `obj` is a live Max object
    unsafe { guard_raw(obj.max_obj(), what, neutral, f) }
}

/// Like [`guard_or`], for methods that return nothing.
#[doc(hidden)]
pub fn guard<O: MaxObjHeader, F: FnOnce()>(obj: &O, what: &str, f: F) {
    guard_or(obj, what, (), f)
}

/// Run `f` where there is no object to report against (`new`, `free`); on a panic, post the
/// message to the console and return `neutral`.
#[doc(hidden)]
pub fn guard_global<R, F: FnOnce() -> R>(what: &str, neutral: R, f: F) -> R {
    guard_with(neutral, f, |msg| {
        crate::max::error(panic_text(what, msg));
    })
}

/// Run the registration code of `ext_main`; on a panic post that `what` failed to register.
/// Never exits the process.
#[doc(hidden)]
pub fn guard_ext_main<F: FnOnce()>(what: &str, f: F) {
    guard_with((), f, |msg| {
        crate::max::error(format!("median: failed to register {}: {}", what, msg));
    })
}

#[cfg(test)]
mod tests {
    use super::*;
    use std::cell::RefCell;

    #[test]
    fn no_panic_passes_value_through() {
        let reported = RefCell::new(None);
        let r = guard_with(0, || 5, |m| *reported.borrow_mut() = Some(m.to_string()));
        assert_eq!(r, 5);
        assert!(reported.borrow().is_none());
    }

    #[test]
    fn str_payload() {
        let reported = RefCell::new(None);
        let r = guard_with(
            -1,
            || -> i32 { panic!("static message") },
            |m| *reported.borrow_mut() = Some(m.to_string()),
        );
        assert_eq!(r, -1);
        assert_eq!(reported.borrow().as_deref(), Some("static message"));
    }

    #[test]
    fn string_payload() {
        let reported = RefCell::new(None);
        let r = guard_with(
            std::ptr::null_mut::<u8>(),
            || -> *mut u8 { panic!("formatted {}", 42) },
            |m| *reported.borrow_mut() = Some(m.to_string()),
        );
        assert!(r.is_null());
        assert_eq!(reported.borrow().as_deref(), Some("formatted 42"));
    }

    #[test]
    fn other_payload() {
        let r = catch(|| std::panic::panic_any(7u32));
        assert_eq!(r, Err("unknown panic payload".to_string()));
    }

    #[test]
    fn panic_text_names_the_method() {
        assert_eq!(panic_text("bang", "oops"), "median: panic in bang: oops");
    }
}
